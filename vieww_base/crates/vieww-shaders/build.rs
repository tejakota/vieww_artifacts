//! Bakes the built-in WGSL library (`shaders/*.wgsl`) to SPIR-V at compile
//! time, so a Vulkan build that uses only built-in shaders needs no shader
//! compiler at run time — see `src/baked.rs` for why.
//!
//! Uses the same `src/spirv_options.rs` the runtime compiler uses, so the two
//! cannot drift; `baked`'s tests compare their bytes.

#[path = "src/spirv_options.rs"]
#[allow(dead_code, unreachable_pub)]
mod spirv_options;

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("shaders");
    println!("cargo::rerun-if-changed=shaders");
    println!("cargo::rerun-if-changed=src/spirv_options.rs");

    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .expect("shaders/ is readable")
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            if path.extension()?.to_str()? != "wgsl" {
                return None;
            }
            Some(path.file_stem()?.to_str()?.to_owned())
        })
        .collect();
    names.sort();

    let mut out = String::from(
        "// @generated by vieww-shaders/build.rs from shaders/*.wgsl. Do not edit.\n\n",
    );
    let mut table = String::from("pub(crate) static BAKED: &[Baked] = &[\n");
    for name in &names {
        let path = dir.join(format!("{name}.wgsl"));
        println!("cargo::rerun-if-changed={}", path.display());
        let wgsl = std::fs::read_to_string(&path).expect("shader is readable");
        let (module, info) = spirv_options::parse_and_validate(&wgsl)
            .unwrap_or_else(|e| panic!("shaders/{name}.wgsl: {e}"));
        let words = spirv_options::write_spirv(&module, &info)
            .unwrap_or_else(|e| panic!("shaders/{name}.wgsl: spir-v: {e}"));
        let ident = name.to_uppercase();
        let _ = write!(out, "static {ident}_SPIRV: [u32; {}] = [", words.len());
        for (i, w) in words.iter().enumerate() {
            if i % 8 == 0 {
                out.push_str("\n    ");
            }
            let _ = write!(out, "0x{w:08x}, ");
        }
        out.push_str("\n];\n");
        let mut entries = String::new();
        for ep in &module.entry_points {
            let stage = match ep.stage {
                naga::ShaderStage::Vertex => "Vertex",
                naga::ShaderStage::Fragment => "Fragment",
                naga::ShaderStage::Compute => "Compute",
                other => panic!("shaders/{name}.wgsl: unsupported stage {other:?}"),
            };
            let _ = write!(entries, "({:?}, Stage::{stage}), ", ep.name);
        }
        let _ = writeln!(
            table,
            "    Baked {{ name: {name:?}, wgsl: include_str!({:?}), spirv: &{ident}_SPIRV, entry_points: &[{entries}] }},",
            path.display().to_string()
        );
    }
    table.push_str("];\n");
    out.push_str(&table);
    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("baked_spirv.rs");
    std::fs::write(dest, out).expect("write baked_spirv.rs");
}
