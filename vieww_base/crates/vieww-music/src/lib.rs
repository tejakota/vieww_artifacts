//! Music as math and code — from Carnatic to rock — rendered by
//! [`vieww_audio`].
//!
//! # One pitch space
//!
//! Every tradition here shares one idea of pitch: a **pitch number**
//! (MIDI-style, 60 = middle C, fractional allowed) played through a
//! **tuning** that says what frequency it sounds at. Twelve-tone equal
//! temperament, just intonation, a raga's swara ratios, 22 shrutis and
//! 53-EDO are all values of [`vieww_audio::synth::tuning::Tuning`]; a raga,
//! a chord and a riff are grammars on top. So "Carnatic to rock" is data,
//! not two engines, and retuning a whole piece is one assignment
//! ([`score::Score::tuning`]).
//!
//! # The layers
//!
//! * [`pitch`] — exact [`pitch::Ratio`]s and cents; the bridge from ratios
//!   to tunings.
//! * [`scala`] — Scala `.scl` files in and out, the microtonal world's
//!   shared format.
//! * [`carnatic`] — swaras; all 72 melakartas **generated by formula**;
//!   ragas as grammars (arohana, avarohana, vakra paths, omitted swaras,
//!   phrases) with a validator; gamakas as continuous pitch curves; the 35
//!   suladi talas and the chapus by construction; korvai/mora arithmetic
//!   that always lands on sam.
//! * [`western`] — modes, chords and roman numerals, minimal-motion voice
//!   leading, Euclidean rhythms and swing.
//! * [`rock`] — power chords, riffs, backbeat kits, the 12-bar form.
//! * [`score`] — the one representation both traditions compile to:
//!   parts of timed events with fractional pitch, velocity and optional
//!   gamaka; exports to [`vieww_audio::sequencer::Clip`]s and Standard MIDI
//!   Files.
//! * [`generate`] — seeded, reproducible generation: raga-grammar walks,
//!   Markov chains, rock progressions.
//! * [`render`] — a score to stereo audio through the engine's voices,
//!   mixer and master chain.
//! * [`pieces`] — three demonstration pieces built from all of the above:
//!   a Carnatic piece in Adi tala, a just-intoned chorale, a 12-bar rock
//!   song.
//!
//! # A taste
//!
//! ```
//! use vieww_music::carnatic::melakarta::Melakarta;
//!
//! // The 15th melakarta, generated, not looked up.
//! let m = Melakarta::new(15).unwrap();
//! assert_eq!(m.name(), "Mayamalavagowla");
//! assert_eq!(m.semitones(), [0, 1, 4, 5, 7, 8, 11]);
//! ```
//!
//! What this crate does **not** claim: that following rules makes music
//! sound idiomatic. The validators check the grammar a tradition writes
//! down; whether a phrase *sounds* like the raga is for musicians to judge.

