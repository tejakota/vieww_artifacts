def verify_window(minimp3_h):
    src = open(minimp3_h).read()
    body = re.search(r"static const float g_win\[\] = \{(.*?)\};", src, re.S).group(1)
    w = [int(v) for v in re.findall(r"-?\d+", body)]
    assert len(w) == 15 * 16
    checked = 0
    for r in range(15):
        for m in range(8):
            a, b = w[r * 16 + 2 * m], w[r * 16 + 2 * m + 1]
            assert ENWINDOW[32 * m + 1 + r] == a, (r, m, a)
            assert -ENWINDOW[32 * m + 31 - r] == b, (r, m, b)
            checked += 2
    pair = re.search(r"static void mp3d_synth_pair.*?\{(.*?)\n\}", src, re.S).group(1)
    consts = [int(v) for v in re.findall(r"\*\s*(-?\d+);", pair)]
    first = consts[:8]   # |C[32m]|, m = 1..8
    for m, c in enumerate(first, 1):
        assert abs(ENWINDOW[32 * m]) == c, (m, c)
        checked += 1
    second = consts[8:]  # C[16 + 32m] for m = 7..0, as minimp3 lists them
    for i, c in enumerate(second):
        m = [1, 3, 5, 7, 6, 4, 2, 0][i]
        assert abs(ENWINDOW[16 + 32 * m]) == abs(c), (m, c)
        checked += 1
    print(f"synthesis window: {checked} entries verified against minimp3", file=sys.stderr)

def parse_huff(path):
    tables, cur, refs = {}, None, {}
    for line in open(path):
        line = line.split("#")[0].strip()
        if not line:
            continue
        if line.startswith(".table"):
            n, xl, yl, lb = map(int, line.split()[1:5])
            cur = n
            tables[n] = {"linbits": lb, "codes": []}
        elif line.startswith(".reference") or line.startswith(".referenz"):
            refs[cur] = int(line.split()[1])
        elif line.startswith(".end"):
            break
        else:
            parts = line.split()
            if cur >= 32:
                val, hlen, hcod = int(parts[0]), int(parts[1]), parts[2]
                x, y = val, 0
            else:
                x, y, hlen, hcod = int(parts[0]), int(parts[1]), int(parts[2]), parts[3]
            assert len(hcod) == hlen
            tables[cur]["codes"].append((int(hcod, 2), hlen, x, y))
    for n, r in refs.items():
        tables[n]["codes"] = None
        tables[n]["ref"] = r
    return tables

