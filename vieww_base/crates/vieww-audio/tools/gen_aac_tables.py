#!/usr/bin/env python3
"""Generate src/codec/aac_tables.rs from VisualOn's vo-aacenc `aac_rom.c`.

Source: https://github.com/mstorsjo/vo-aacenc (aacenc/src/aac_rom.c),
Copyright 2003-2010 VisualOn, Inc., Apache License 2.0 — the same license as
this repository. The tables are ISO/IEC 14496-3 data: the spectral Huffman
codebooks 1–11, the scalefactor codebook, and the scalefactor-band offsets
for long and short windows per sampling-frequency index.

Usage: gen_aac_tables.py path/to/aac_rom.c > ../src/codec/aac_tables.rs
Every codebook is checked to be a complete prefix code (Kraft sum 1).
"""
import re, sys

src = open(sys.argv[1]).read()

def arr(name):
    m = re.search(r"const\s+\w+\s+" + re.escape(name) + r"((?:\[\w+\])+)\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("missing " + name)
    body = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
    return [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|-?\d+", body)]

# (book, lengths array, byte: 1 = high, 0 = low, dims, signed, lav)
spec = [
    (1, "huff_ltab1_2", 1, 4, True, 1), (2, "huff_ltab1_2", 0, 4, True, 1),
    (3, "huff_ltab3_4", 1, 4, False, 2), (4, "huff_ltab3_4", 0, 4, False, 2),
    (5, "huff_ltab5_6", 1, 2, True, 4), (6, "huff_ltab5_6", 0, 2, True, 4),
    (7, "huff_ltab7_8", 1, 2, False, 7), (8, "huff_ltab7_8", 0, 2, False, 7),
    (9, "huff_ltab9_10", 1, 2, False, 12), (10, "huff_ltab9_10", 0, 2, False, 12),
    (11, "huff_ltab11", 0, 2, False, 16),
]
out = ["//! AAC constant tables — generated by `tools/gen_aac_tables.py`; do not edit.",
       "//! ISO/IEC 14496-3 data as carried by VisualOn's vo-aacenc (`aac_rom.c`,",
       "//! Copyright 2003-2010 VisualOn, Inc., Apache License 2.0).", "",
       "/// A codeword: (code, length, then up to four values).",
       "pub(super) type Entry = (u32, u8, i8, i8, i8, i8);", ""]
books = []
for book, ltab, hi, dims, signed, lav in spec:
    lens = arr(ltab)
    codes = arr(f"huff_ctab{book}")
    assert len(lens) == len(codes), (book, len(lens), len(codes))
    entries = []
    side = 2 * lav + 1 if signed else lav + 1
    kraft = 0.0
    for i, (l, c) in enumerate(zip(lens, codes)):
        ln = (l >> 8) & 0xFF if hi else l & 0xFF
        # Unpack the index into per-dimension values.
        vals, k = [], i
        for _ in range(dims):
            vals.append(k % side)
            k //= side
        vals = vals[::-1]
        if signed:
            vals = [v - lav for v in vals]
        vals += [0] * (4 - dims)
        assert 0 < ln <= 19 and c < (1 << ln), (book, i, ln, c)
        entries.append((c, ln, *vals))
        kraft += 2.0 ** -ln
    assert abs(kraft - 1.0) < 1e-12, (book, kraft)
    items = ", ".join(f"({c}, {l}, {a}, {b}, {cc}, {d})" for c, l, a, b, cc, d in entries)
    out.append(f"const B{book}: &[Entry] = &[{items}];")
    books.append(f"B{book}")
out.append("")
out.append("/// Spectral codebooks 1–11 (index 0 unused): (code, length, values…).")
out.append(f"pub(super) const BOOKS: [&[Entry]; 12] = [&[], {', '.join(books)}];")
sl = arr("huff_ltabscf")
sc = arr("huff_ctabscf")
assert len(sl) == len(sc) == 121
assert abs(sum(2.0 ** -l for l in sl) - 1.0) < 1e-12
out.append("/// Scalefactor codebook: (code, length) for differences −60..=60.")
out.append(f"pub(super) const SCF: [(u32, u8); 121] = [{', '.join(f'({c}, {l})' for c, l in zip(sc, sl))}];")
lo = arr("sfBandTabLongOffset"); lt = arr("sfBandTabLong")
so = arr("sfBandTabShortOffset"); st = arr("sfBandTabShort")
nl = arr("sfBandTotalLong"); ns = arr("sfBandTotalShort")
longs, shorts = [], []
for i in range(12):
    l = lt[lo[i]:lo[i] + nl[i] + 1]
    s = st[so[i]:so[i] + ns[i] + 1]
    assert l[0] == 0 and l[-1] == 1024 and s[0] == 0 and s[-1] == 128, i
    longs.append(l); shorts.append(s)
fmt = lambda rows: "[" + ", ".join("&[" + ", ".join(map(str, r)) + "]" for r in rows) + "]"
out.append("/// Long-window band offsets per sampling-frequency index (96 kHz … 8 kHz).")
out.append(f"pub(super) const SWB_LONG: [&[u16]; 12] = {fmt(longs)};")
out.append("/// Short-window band offsets per sampling-frequency index.")
out.append(f"pub(super) const SWB_SHORT: [&[u16]; 12] = {fmt(shorts)};")
print("\n".join(out))
print("books verified complete", file=sys.stderr)
