/// The editor pane: tab row, gutter, code lines, caret, optional sweep.
/// `tab` overrides the buffer tab's name (S16's `endcard` buffer).
pub(crate) fn editor(
    code: &Code,
    blur: f32,
    err_token: Option<(usize, usize)>,
    tab: Option<&str>,
) -> WidgetNode {
    let w = ED_X1 - ED_X0;
    let mut stack = Stack::new();

    // Tab row.
    let tab_name = tab.unwrap_or(match code {
        Code::Rust { .. } => "counter.rs",
        _ => "counter.say",
    });
    stack = stack.push(
        Positioned::new()
            .left(0.0)
            .top(0.0)
            .width(w)
            .height(44.0)
            .child(Painting::sized(
                Size::new(w, 44.0),
                PaintWith::new(move |book: &mut Sketchbook, s: Size| {
                    book.rect(
                        xywh(0.0, 0.0, s.width, 44.0),
                        alpha(Color::rgb(13, 13, 17), 0.9),
                    );
                    book.rect(xywh(0.0, 43.0, s.width, 1.0), alpha(Color::WHITE, 0.06));
                }),
            )),
    );
    stack = stack
        .push(
            Positioned::new()
                .left(14.0)
                .top(9.0)
                .width(240.0)
                .height(28.0)
                .child(
                    Container::new()
                        .color(alpha(Color::rgb(26, 24, 36), 0.95))
                        .radius(8.0)
                        .border(vieww_foundation::Border::new(alpha(VIOLET_SOFT, 0.35), 1.0))
                        .child(
                            Text::new(tab_name)
                                .style(TextStyle::new(15.0).monospace().color(alpha(INK, 0.9)))
                                .align(TextAlign::Center),
                        ),
                ),
        )
        .push(
            Positioned::new()
                .left(272.0)
                .top(13.0)
                .width(300.0)
                .height(22.0)
                .child(
                    Text::new("+ say buffer")
                        .style(TextStyle::new(13.5).monospace().color(alpha(FAINT, 0.7))),
                ),
        );

    // The code area.
    let (lines, typed_chars, sweep) = display_lines(code);
    let n_lines = lines.len();

    let mut code_stack = Stack::new();
    for i in 0..n_lines {
        code_stack = code_stack.push(
            Positioned::new()
                .left(8.0)
                .top(10.0 + i as f32 * CODE_LH)
                .width(50.0)
                .height(26.0)
                .child(mono((i + 1).to_string(), 15.0, alpha(FAINT, 0.5))),
        );
    }

    // The lines themselves — typed prefix in say mode, full lines otherwise.
    let mut chars_used = 0usize;
    for (li, line) in lines.iter().enumerate() {
        let mut x = 0.0f32;
        for (seg_text, seg_color) in line {
            let seg_chars = seg_text.chars().count();
            let visible_from = chars_used;
            chars_used += seg_chars;
            let typed_ok = match typed_chars {
                None => true,
                Some(t) => t >= visible_from,
            };
            if !typed_ok {
                let t = typed_chars.unwrap();
                let part = t.saturating_sub(visible_from);
                if part > 0 {
                    let prefix: String = seg_text.chars().take(part).collect();
                    code_stack = code_stack.push(
                        Positioned::new()
                            .left(CODE_X + x)
                            .top(10.0 + li as f32 * CODE_LH)
                            .width(super::mono_w(CODE_SIZE, part) + 8.0)
                            .height(28.0)
                            .child(mono(prefix, CODE_SIZE, *seg_color)),
                    );
                }
                continue;
            }
            code_stack = code_stack.push(
                Positioned::new()
                    .left(CODE_X + x)
                    .top(10.0 + li as f32 * CODE_LH)
                    .width(super::mono_w(CODE_SIZE, seg_chars) + 8.0)
                    .height(28.0)
                    .child(mono(*seg_text, CODE_SIZE, *seg_color)),
            );
            x += super::mono_w(CODE_SIZE, seg_chars);
        }
    }

    // The caret — rides the typing head while say types; blinks at the
    // wait's own 24-in-60 cadence.
    let blink = match code {
        Code::Say { blink, .. } => Some(*blink),
        Code::SayExt { blink, .. } => Some(*blink),
        _ => None,
    };
    if let (Some(t), Some(bl)) = (typed_chars, blink) {
        let (mut cx, mut cy) = (CODE_X, 10.0f32);
        let mut used = 0usize;
        'outer: for (li, line) in lines.iter().enumerate() {
            let mut x = 0.0f32;
            for (seg_text, _) in line {
                let n = seg_text.chars().count();
                if used + n > t {
                    let part = t - used;
                    cx = CODE_X + x + super::mono_w(CODE_SIZE, part);
                    cy = 10.0 + li as f32 * CODE_LH;
                    break 'outer;
                }
                used += n;
                x += super::mono_w(CODE_SIZE, n);
            }
        }
        let on = (bl * 2.6).fract() < 0.62;
        if on {
            code_stack = code_stack.push(
                Positioned::new()
                    .left(cx)
                    .top(cy + 3.0)
                    .width(2.6)
                    .height(24.0)
                    .child(Container::new().color(alpha(VIOLET_SOFT, 0.9)).radius(1.3)),
            );
        }
    }

    // The error token underline — a red wave under the offending word.
    if let Some((line_i, char_i)) = err_token {
        let y = 10.0 + line_i as f32 * CODE_LH + 27.0;
        let x = CODE_X + super::mono_w(CODE_SIZE, char_i);
        let wlen = super::mono_w(CODE_SIZE, 5);
        code_stack = code_stack.push(
            Positioned::new()
                .left(x)
                .top(y)
                .width(wlen + 6.0)
                .height(8.0)
                .child(Painting::sized(
                    Size::new(wlen + 6.0, 8.0),
                    PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                        let mut p = vieww_foundation::Path::new();
                        p.move_to(Offset::new(0.0, 4.0));
                        let n = 6;
                        for i in 0..=n {
                            let k = i as f32 / n as f32;
                            p.line_to(Offset::new(k * wlen, if i % 2 == 0 { 1.5 } else { 5.5 }));
                        }
                        book.stroke(p, alpha(RED, 0.85), 1.6);
                    }),
                )),
        );
    }

    stack = stack.push(
        Positioned::new()
            .left(0.0)
            .top(44.0)
            .width(w)
            .height(940.0)
            .child(
                Stack::new()
                    .push(
                        Positioned::fill()
                            .child(Container::new().color(alpha(Color::rgb(11, 11, 15), 0.92))),
                    )
                    .push(
                        Positioned::new()
                            .left(56.0)
                            .top(0.0)
                            .width(w - 56.0)
                            .height(940.0)
                            .child(code_stack),
                    ),
            ),
    );

    // The sweep — a vertical scan line crossing the editor (E-06).
    if let Some(sw) = sweep {
        if sw > 0.001 && sw < 0.999 {
            let sx = sw * w;
            stack = stack.push(
                Positioned::new()
                    .left(0.0)
                    .top(44.0)
                    .width(w)
                    .height(940.0)
                    .child(Painting::sized(
                        Size::new(w, 940.0),
                        PaintWith::new(move |book: &mut Sketchbook, s: Size| {
                            book.layer(1.0, 0.0, None, |g| {
                                g.rect(xywh(sx - 26.0, 0.0, 52.0, s.height), alpha(VIOLET, 0.10));
                            });
                            book.rrect(
                                xywh(sx - 1.2, 0.0, 2.4, s.height),
                                1.2,
                                alpha(tint(VIOLET_SOFT, 0.3), 0.85),
                            );
                        }),
                    )),
            );
        }
    }

    if blur > 0.05 {
        Filtered::blur(blur).child(stack).into()
    } else {
        stack.into()
    }
}

