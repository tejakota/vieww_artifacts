/// A studio specification — what a scene wants in each pane.
pub(crate) struct Spec {
    pub code: Code,
    pub app: App,
    pub editor_blur: f32,
    pub preview_blur: f32,
    pub show_preview: bool,
    pub err_token: Option<(usize, usize)>,
    /// The live build badge (frames built so far — the harness's own count).
    pub build_badge: Option<u64>,
    /// A damage rect over the preview (probe geometry), with its label.
    pub damage: Option<(Rect, String)>,
    /// The performance strip over the preview.
    pub perf_strip: bool,
    /// The session line's progress under everything (E-17).
    pub session_line: f32,
    /// Extra overlay content, drawn above the studio (scene-specific).
    pub overlay: Option<WidgetNode>,
    /// The buffer tab's name, when a scene overrides it.
    pub tab: Option<String>,
    /// ms readout for the status bar.
    pub ms: Option<f32>,
    pub px: Option<u32>,
}

impl Default for Spec {
    fn default() -> Self {
        Spec {
            code: Code::Empty,
            app: App::new(0, 0.0, 0.0),
            editor_blur: 0.0,
            preview_blur: 0.0,
            show_preview: true,
            err_token: None,
            build_badge: None,
            damage: None,
            perf_strip: false,
            session_line: 0.0,
            overlay: None,
            tab: None,
            ms: None,
            px: None,
        }
    }
}

/// The whole studio, positioned full-bleed at master scale.
pub(crate) fn studio(abs: f32, ladder: u32, spec: Spec) -> WidgetNode {
    let Spec {
        code,
        app,
        editor_blur,
        preview_blur,
        show_preview,
        err_token,
        build_badge,
        damage,
        perf_strip: show_perf,
        session_line: line_frac,
        overlay,
        tab,
        ms,
        px,
    } = spec;

    let mut root = Stack::new()
        .push(
            Positioned::fill().child(
                Container::new()
                    .size(1920.0, 1080.0)
                    .color(alpha(Color::rgb(10, 10, 13), 1.0)),
            ),
        )
        .push(
            Positioned::new()
                .left(0.0)
                .top(0.0)
                .width(1920.0)
                .height(TITLE_H)
                .child(title_bar()),
        )
        .push(
            Positioned::new()
                .left(0.0)
                .top(TITLE_H)
                .width(ACT_W)
                .height(1080.0 - TITLE_H - STATUS_H)
                .child(activity_bar()),
        )
        .push(
            Positioned::new()
                .left(ED_X0)
                .top(TITLE_H)
                .width(ED_X1 - ED_X0)
                .height(1080.0 - TITLE_H - STATUS_H)
                .child(editor(&code, editor_blur, err_token, tab.as_deref())),
        );

    if show_preview {
        root = root.push(
            Positioned::new()
                .left(PV_X0)
                .top(TITLE_H + 30.0)
                .width(PV_X1 - PV_X0)
                .height(PV_H + 34.0)
                .child(preview(&app, preview_blur)),
        );
    }

    if let Some(built) = build_badge {
        root = root.push(
            Positioned::new()
                .left(ED_X1 - 250.0)
                .top(TITLE_H + 56.0)
                .width(230.0)
                .height(36.0)
                .child(chip(
                    format!("builds {}", group_commas(built)),
                    13.0,
                    tint(VIOLET_SOFT, 0.2),
                )),
        );
    }

    if let Some((rect, label)) = damage {
        let r = rect;
        root = root.push(
            Positioned::new()
                .left(PV_X0 + r.left)
                .top(TITLE_H + 64.0 + r.top)
                .width(r.width() + 4.0)
                .height(r.height() + 4.0)
                .child(Painting::sized(
                    Size::new(r.width() + 4.0, r.height() + 4.0),
                    PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                        book.stroke_rrect(
                            xywh(0.0, 0.0, r.width(), r.height()),
                            8.0,
                            alpha(C_DAMAGE, 0.9),
                            1.6,
                        );
                        book.rrect(
                            xywh(0.0, 0.0, r.width(), r.height()),
                            8.0,
                            alpha(C_DAMAGE, 0.08),
                        );
                    }),
                )),
        );
        root = root.push(
            Positioned::new()
                .left(PV_X0 + r.left)
                .top(TITLE_H + 40.0 + r.top)
                .width(420.0)
                .height(22.0)
                .child(
                    Text::new(label).style(
                        TextStyle::new(13.0)
                            .monospace()
                            .color(alpha(tint(RED, 0.35), 0.95)),
                    ),
                ),
        );
    }

    if show_perf {
        root = root.push(
            Positioned::new()
                .left(PV_X0)
                .top(TITLE_H + 46.0)
                .width(PV_X1 - PV_X0)
                .height(64.0)
                .child(perf_strip(abs)),
        );
    }

    if line_frac > 0.001 {
        let frac = line_frac;
        root = root.push(Positioned::fill().child(Painting::sized(
            Size::new(1920.0, 1080.0),
            PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                session_line(book, frac, abs);
            }),
        )));
    }

    root = root.push(
        Positioned::new()
            .left(0.0)
            .top(1080.0 - STATUS_H)
            .width(1920.0)
            .height(STATUS_H)
            .child(status_bar(abs, ladder, ms, px)),
    );

    if let Some(ov) = overlay {
        root = root.push(Positioned::fill().child(ov));
    }

    root.into()
}

/// The session line — the film's spine, from the buffer to the preview and
/// onward. Nodes are touches; the stroke is the session's continuity.
pub(crate) fn session_line(book: &mut Sketchbook, frac: f32, abs: f32) {
    let y = 1006.0;
    let x0 = 214.0;
    let x1 = 1010.0;
    let pts = [
        Offset::new(x0, y),
        Offset::new(x0 + 240.0, y),
        Offset::new(x0 + 460.0, y - 44.0),
        Offset::new(x1, y - 44.0),
    ];
    let mut p = vieww_foundation::Path::new();
    p.move_to(pts[0]);
    for pt in pts.iter().skip(1) {
        p.line_to(*pt);
    }
    book.stroke(p.clone(), alpha(Color::WHITE, 0.07), 1.2);
    // The progressive stroke — one dash, phase-advanced (E-17).
    let total = 240.0 + 258.7 + 460.0;
    let draw = total * clamp01(frac);
    book.stroke_styled(
        p,
        alpha(VIOLET_SOFT, 0.9),
        2.0,
        vieww_foundation::StrokeStyle::default()
            .dash(vieww_foundation::Dash::new(vec![draw, total + 2.0])),
    );
    let nodes = [
        (x0, y, 1.0),
        (x0 + 240.0, y, 2.0),
        (x0 + 460.0, y - 44.0, 4.0),
        (x1, y - 44.0, 6.0),
    ];
    for (nx, ny, tap_n) in nodes {
        let lit = super::ladder_at(abs) >= tap_n as u32;
        book.circle(
            Offset::new(nx, ny),
            if lit { 5.0 } else { 3.0 },
            if lit {
                alpha(VIOLET_SOFT, 0.95)
            } else {
                alpha(MUTED, 0.3)
            },
        );
    }
}

/// The performance strip — FrameStats as a ribbon: frame bars + damage
/// history, all derived from the session clock.
pub(crate) fn perf_strip(abs: f32) -> WidgetNode {
    let w = PV_X1 - PV_X0;
    Painting::sized(
        Size::new(w, 64.0),
        PaintWith::new(move |book: &mut Sketchbook, s: Size| {
            book.rrect(
                xywh(0.0, 0.0, s.width, 64.0),
                10.0,
                alpha(Color::rgb(14, 14, 19), 0.9),
            );
            book.stroke_rrect(
                xywh(0.0, 0.0, s.width, 64.0),
                10.0,
                alpha(Color::WHITE, 0.08),
                1.0,
            );
            let n = 60;
            let bw = (s.width - 24.0) / n as f32;
            for i in 0..n {
                let phase = abs * 6.0 - i as f32 * 0.42;
                let hgt = 8.0 + 22.0 * (0.5 + 0.5 * phase.sin());
                let x = 12.0 + i as f32 * bw;
                book.rect(
                    xywh(x, 52.0 - hgt, bw * 0.66, hgt),
                    if i == n - 1 {
                        alpha(VIOLET_SOFT, 0.95)
                    } else {
                        alpha(VIOLET, 0.30)
                    },
                );
            }
            let mut p = vieww_foundation::Path::new();
            for i in 0..40 {
                let k = i as f32 / 39.0;
                let x = 12.0 + k * (s.width - 24.0);
                let v = if (i as f32 * 0.7 + abs * 3.0).sin() > 0.45 {
                    1.0
                } else {
                    0.12
                };
                let y = 58.0 - v * 6.0;
                if i == 0 {
                    p.move_to(Offset::new(x, y));
                } else {
                    p.line_to(Offset::new(x, y));
                }
            }
            book.stroke(p, alpha(C_DAMAGE, 0.75), 1.4);
        }),
    )
    .into()
}
