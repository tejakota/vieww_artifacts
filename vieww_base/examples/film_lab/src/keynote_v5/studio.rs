/// The file-tree sidebar — the workspace: the counter project the session
/// edits, plus the plates the demos will drop in.
pub fn file_tree(seed: u64, t: f32, progress: f32) -> WidgetNode {
    let entries: [(&str, u8); 10] = [
        ("v counter/", 0),
        ("  Cargo.toml", 1),
        ("  counter.say", 2),
        ("  counter.rs", 3),
        ("  assets/", 1),
        ("v experiments/", 0),
        ("  swarm.say", 4),
        ("  fourier.say", 5),
        ("  plates/", 1),
        ("  receipts.txt", 3),
    ];
    let p = clamp01(progress);
    Painting::sized(
        Size::new(SIDE_W, 1080.0 - TITLE_H - STATUS_H),
        PaintWith::new(move |book: &mut Sketchbook, s: Size| {
            book.rect(xywh(0.0, 0.0, s.width, s.height), alpha(Color::rgb(12, 12, 16), 0.96));
            book.rect(xywh(s.width - 1.0, 0.0, 1.0, s.height), alpha(Color::WHITE, 0.05));
            // The workspace header.
            book.rect(xywh(0.0, 0.0, s.width, 30.0), alpha(Color::rgb(15, 15, 20), 0.9));
            book.rect(xywh(16.0, 12.0, 10.0, 10.0), alpha(VIOLET_SOFT, 0.7));
            // The entries, arriving one by one.
            let n = entries.len();
            let shown = (n as f32 * p).ceil() as usize;
            for (i, (name, kind)) in entries.iter().enumerate() {
                if i >= shown {
                    break;
                }
                let y = 52.0 + i as f32 * 30.0;
                let c = match kind {
                    0 => alpha(INK, 0.9),
                    2 | 4 | 5 => alpha(VIOLET_SOFT, 0.95),
                    3 => alpha(MUTED, 0.9),
                    _ => alpha(MUTED, 0.8),
                };
                let indent = 20.0 + if name.starts_with("  ") { 18.0 } else { 0.0 };
                // The caret / file glyph.
                if name.starts_with('v') {
                    let mut tri = vieww_foundation::Path::new();
                    tri.move_to(Offset::new(indent - 14.0, y - 4.0));
                    tri.line_to(Offset::new(indent - 14.0, y + 4.0));
                    tri.line_to(Offset::new(indent - 7.0, y));
                    tri.close();
                    book.fill(tri, alpha(MUTED, 0.8));
                } else {
                    book.rect(xywh(indent - 13.0, y - 5.0, 9.0, 11.0), alpha(FAINT, 0.55));
                }
                book.rect(xywh(indent, y - 7.0, name.trim_end_matches('/').len() as f32 * 8.4 + 8.0, 16.0), alpha(Color::TRANSPARENT, 0.0));
                let _ = c;
                // Label — drawn as mono text via thin rects is wasteful; the
                // sidebar's names ride as text nodes above this paint. Here
                // we only lay the rail's texture.
                book.rect(xywh(indent, y + 14.0, name.len().min(20) as f32 * 7.6, 1.0), alpha(Color::WHITE, 0.03));
            }
            // Breathing life — the workspace's own pulse.
            let glow_a = 0.05 + 0.03 * (t * 2.0 + seed as f32 * 0.1).sin();
            book.layer(1.0, 18.0, None, |g| {
                g.circle(
                    Offset::new(s.width * 0.5, s.height * 0.32),
                    s.width * 0.8,
                    Gradient::radial_fill().with_dither().with_stops(&[
                        (0.0, alpha(VIOLET, glow_a)),
                        (1.0, alpha(VIOLET, 0.0)),
                    ]),
                );
            });
        }),
    )
    .into()
}

