/// One tokenized code line: text run + color.
pub type Seg = (&'static str, Color);

/// The counter buffer in say — verbatim grammar from the studio's own
/// `06-say.md` (the film's first shown code; the language is the product's).
pub fn say_lines() -> Vec<Vec<Seg>> {
    let kw = VIOLET_SOFT;
    let st = AMBER;
    let nu = MINT;
    let tx = CODE_PLAIN;
    let pu = MUTED;
    vec![
        vec![("keep ", kw), ("a whole number called ", tx), ("count", tx), (" starting at ", pu), ("0", nu)],
        vec![],
        vec![("screen ", kw), ("\"Home\"", st), (":", pu)],
        vec![("    a column, spaced ", pu), ("16", nu), (", children aligned to the start:", pu)],
        vec![("        a heading ", pu), ("\"Counter\"", st)],
        vec![("        a label ", pu), ("\"Tapped \\(count) times\"", st)],
        vec![("        a button ", pu), ("\"Add one\"", st), (" which when tapped:", pu)],
        vec![("            add ", kw), ("1", nu), (" to count", tx)],
    ]
}

/// The same buffer, descended — the generated Rust, annotated the way
/// `say-codegen` annotates (`// say: file:line`), state held across the
/// switch. The counter never resets through the morph.
pub fn rust_lines() -> Vec<Vec<Seg>> {
    let cm = FAINT;
    let at = VIOLET;
    let kw = VIOLET_SOFT;
    let ty = CYAN;
    let st = AMBER;
    let nu = MINT;
    let tx = CODE_PLAIN;
    let pu = MUTED;
    vec![
        vec![("// say: counter.say — generated by vieww-say-codegen", cm)],
        vec![("#[vieww::keep]", at)],
        vec![("static ", kw), ("COUNT", ty), (": ", pu), ("Signal", ty), ("<", pu), ("u32", ty), ("> = ", pu), ("Signal", ty), ("::new(", pu), ("0", nu), (");", pu)],
        vec![],
        vec![("#[vieww::screen(name = ", at), ("\"Home\"", st), (")]", at)],
        vec![("fn ", kw), ("home", tx), ("() -> ", pu), ("impl Widget", ty), (" {", pu)],
        vec![("    column", ty), ("(", pu), ("16", nu), (").align_start().children([", pu)],
        vec![("        heading", ty), ("(", pu), ("\"Counter\"", st), ("),", pu)],
        vec![("        label", ty), ("(", pu), ("format!(", pu), ("\"Tapped {} times\"", st), (", ", pu), ("*COUNT.get())", tx)],
        vec![("        button", ty), ("(", pu), ("\"Add one\"", st), (").on_tap(||", pu)],
        vec![("            *COUNT.update(", tx), ("|c| c + ", pu), ("1", nu), ("))),", tx)],
        vec![("    ])", pu)],
        vec![("}", pu)],
    ]
}

/// Which buffer the editor holds.
pub enum Code {
    /// say, typed on — `typed` in `[0, 1]` is the type-on progress,
    /// `blink` the caret's 24-in-60 blink phase.
    Say { typed: f32, blink: f32 },
    /// say, base complete, plus scene-provided extra lines (the buffer
    /// growing under live keystrokes — S12). `lines` are already sliced
    /// to whatever the scene wants visible; the caret rides their end.
    SayExt { blink: f32, lines: Vec<Vec<Seg>> },
    /// A bespoke buffer — the demo plates' own say programs (S14/S15):
    /// complete lines, the caret breathing at the end.
    Lines { lines: Vec<Vec<Seg>>, blink: f32 },
    /// Rust, resolving under the sweep — `sweep` in `[0, 1]` is how far the
    /// scan line has crossed the editor; a line flips once it has passed.
    Rust { sweep: f32 },
    /// Nothing yet — the buffer before the first keystroke.
    Empty,
}

/// The resolved display lines for a code state, with (line-flip) progress.
fn display_lines(code: &Code) -> (Vec<Vec<Seg>>, Option<usize>, Option<f32>) {
    match code {
        Code::Say { typed, .. } => {
            let all = say_lines();
            let total: usize = all
                .iter()
                .map(|l| l.iter().map(|(s, _)| s.chars().count()).sum::<usize>())
                .sum();
            let typed_n = (total as f32 * typed.clamp(0.0, 1.0)).round() as usize;
            (all, Some(typed_n), None)
        }
        Code::SayExt { lines, .. } => {
            let mut all = say_lines();
            let extras = lines.clone();
            all.extend(extras);
            let total: usize = all
                .iter()
                .map(|l| l.iter().map(|(s, _)| s.chars().count()).sum::<usize>())
                .sum();
            (all, Some(total), None)
        }
        Code::Lines { lines, .. } => {
            let all = lines.clone();
            let total: usize = all
                .iter()
                .map(|l| l.iter().map(|(s, _)| s.chars().count()).sum::<usize>())
                .sum();
            (all, Some(total), None)
        }
        Code::Rust { sweep } => {
            let say = say_lines();
            let rust = rust_lines();
            let n = rust.len();
            let mut lines = Vec::with_capacity(n);
            for (i, rline) in rust.iter().enumerate() {
                let passed = *sweep >= (i + 1) as f32 / n as f32;
                if passed {
                    lines.push(rline.clone());
                } else if i < say.len() {
                    lines.push(say[i].clone());
                } else {
                    lines.push(vec![]);
                }
            }
            (lines, None, Some(*sweep))
        }
        Code::Empty => (vec![], None, None),
    }
}

