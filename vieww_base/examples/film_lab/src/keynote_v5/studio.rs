/// The session line — the film's spine, from the buffer to the preview and
/// onward. Nodes are touches; the stroke is the session's continuity.
pub fn session_line(book: &mut Sketchbook, frac: f32, abs: f32) {
    let y = 1006.0;
    let x0 = 214.0;
    let x1 = 1010.0;
    let pts = [
        Offset::new(x0, y),
        Offset::new(x0 + 240.0, y),
        Offset::new(x0 + 460.0, y - 44.0),
        Offset::new(x1, y - 44.0),
    ];
    let mut p = vieww_foundation::Path::new();
    p.move_to(pts[0]);
    for pt in pts.iter().skip(1) {
        p.line_to(*pt);
    }
    book.stroke(p.clone(), alpha(Color::WHITE, 0.07), 1.2);
    // The progressive stroke — one dash, phase-advanced.
    let total = 240.0 + 258.7 + 460.0;
    let draw = total * clamp01(frac);
    book.stroke_styled(
        p,
        alpha(VIOLET_SOFT, 0.9),
        2.0,
        vieww_foundation::StrokeStyle::default()
            .dash(vieww_foundation::Dash::new(vec![draw, total + 2.0])),
    );
    let nodes = [
        (x0, y, 1.0),
        (x0 + 240.0, y, 2.0),
        (x0 + 460.0, y - 44.0, 4.0),
        (x1, y - 44.0, 6.0),
    ];
    for (nx, ny, tap_n) in nodes {
        let lit = super::ladder_at(abs) >= tap_n as u32;
        book.circle(
            Offset::new(nx, ny),
            if lit { 5.0 } else { 3.0 },
            if lit { alpha(VIOLET_SOFT, 0.95) } else { alpha(MUTED, 0.3) },
        );
    }
}

/// The performance strip — FrameStats as a ribbon: frame bars + damage
/// history, all derived from the session clock.
pub fn perf_strip(abs: f32) -> WidgetNode {
    let w = PV_X1 - PV_X0;
    Painting::sized(Size::new(w, 64.0), PaintWith::new(move |book: &mut Sketchbook, s: Size| {
        book.rrect(xywh(0.0, 0.0, s.width, 64.0), 10.0, alpha(Color::rgb(14, 14, 19), 0.9));
        book.stroke_rrect(xywh(0.0, 0.0, s.width, 64.0), 10.0, alpha(Color::WHITE, 0.08), 1.0);
        let n = 60;
        let bw = (s.width - 24.0) / n as f32;
        for i in 0..n {
            let phase = abs * 6.0 - i as f32 * 0.42;
            let hgt = 8.0 + 22.0 * (0.5 + 0.5 * phase.sin());
            let x = 12.0 + i as f32 * bw;
            book.rect(
                xywh(x, 52.0 - hgt, bw * 0.66, hgt),
                if i == n - 1 { alpha(VIOLET_SOFT, 0.95) } else { alpha(VIOLET, 0.30) },
            );
        }
        let mut p = vieww_foundation::Path::new();
        for i in 0..40 {
            let k = i as f32 / 39.0;
            let x = 12.0 + k * (s.width - 24.0);
            let v = if (i as f32 * 0.7 + abs * 3.0).sin() > 0.45 { 1.0 } else { 0.12 };
            let y = 58.0 - v * 6.0;
            if i == 0 {
                p.move_to(Offset::new(x, y));
            } else {
                p.line_to(Offset::new(x, y));
            }
        }
        book.stroke(p, alpha(C_DAMAGE, 0.75), 1.4);
    }))
    .into()
}
