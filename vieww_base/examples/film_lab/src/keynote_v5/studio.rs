/// The preview's app state, all derived from the film's own clocks.
pub struct App {
    /// The witness counter — what the app shows.
    pub number: u32,
    /// Bloom on the number right after a tap (tap_pulse).
    pub flash: f32,
    /// The dial's presence, `[0, 1]`.
    pub dial: f32,
    /// The spring toy's phase source (absolute film seconds — the spring
    /// never restarts, that is the whole point of the carry).
    pub spring_abs: f32,
    /// The spring toy's presence.
    pub spring: f32,
    /// The error boundary's presence, `[0, 1]` — a boundary, not a crash.
    pub error: f32,
    /// The app's alive-bloom (first paint).
    pub alive: f32,
    /// The column's spacing re-flow (16 → 24) — the carry demonstrated as
    /// layout shift while state holds.
    pub spacing: f32,
    /// The heading's live-edit progress toward its new text (S12).
    pub heading: f32,
}

impl App {
    pub fn new(number: u32, flash: f32, abs: f32) -> App {
        App {
            number,
            flash,
            dial: 0.0,
            spring_abs: abs,
            spring: 0.0,
            error: 0.0,
            alive: 1.0,
            spacing: 0.0,
            heading: 0.0,
        }
    }

    /// The heading's current text — "Counter" edits to "viewwstudio" under
    /// the composer's keystrokes (S12); `heading` is the edit's progress.
    pub fn heading_text(&self) -> String {
        const FROM: &str = "Counter";
        const TO: &str = "viewwstudio";
        let u = clamp01(self.heading);
        if u <= 0.0 {
            return FROM.to_string();
        }
        if u >= 1.0 {
            return TO.to_string();
        }
        // A scramble band crossing the word — the compose made visible.
        let n = TO.chars().count();
        let crossed = (n as f32 * u).round() as usize;
        TO.chars().take(crossed).chain(FROM.chars().skip(crossed.min(FROM.chars().count()))).collect()
    }
}

/// The button's rect in preview-local coordinates — the damage probe's
