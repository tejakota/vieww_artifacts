/// A local circle path (the painter's own space).
fn circle_local(cx: f32, cy: f32, r: f32) -> vieww_foundation::Path {
    circle_path(cx, cy, r, 36)
}

/// The preview panel: frosted glass, the app (or a scene's custom sheet)
/// inside. `custom` replaces the counter app when a demo plate drops in.
pub fn preview(app: &App, blur: f32, custom: Option<WidgetNode>) -> WidgetNode {
    let alive = clamp01(app.alive);
    let pane_w = PV_X1 - PV_X0;

    let content = match custom {
        Some(node) => node,
        None => counter_app(app, alive, pane_w),
    };

    // The glass body — frosted, tinted, bordered (light's card grammar).
    let glass = Container::new()
        .size(pane_w, PV_H)
        .radius(18.0)
        .gradient(
            Gradient::vertical().with_dither().with_stops(&[
                (0.0, alpha(mix(Color::WHITE, VIOLET_SOFT, 0.22), 0.055)),
                (0.55, alpha(Color::WHITE, 0.028)),
                (1.0, alpha(mix(Color::WHITE, CYAN_SOFT, 0.28), 0.045)),
            ]),
        )
        .border(vieww_foundation::Border::new(alpha(Color::WHITE, 0.14), 1.0));

    let header = Positioned::new().left(4.0).top(8.0).width(600.0).height(26.0).child(
        Text::new("preview · Home").style(
            TextStyle::new(15.0).monospace().letter_spacing(2.0).color(alpha(MUTED, 0.85)),
        ),
    );

    let pane = Stack::new()
        .push(
            Positioned::new().left(0.0).top(34.0).width(pane_w).height(PV_H).child(glass),
        )
        .push(
            Positioned::new().left(0.0).top(34.0).width(pane_w).height(PV_H).child(content),
        )
        .push(header);

    if blur > 0.05 {
        Filtered::blur(blur).child(pane).into()
    } else {
        pane.into()
    }
}

/// The counter app — heading, label, the number, the button, the toys.
fn counter_app(app: &App, alive: f32, pane_w: f32) -> WidgetNode {
    let number = app.number;
    let flash = app.flash;
    let heading = app.heading_text();
    let heading_a = clamp01(app.heading);
    let spacing_shift = clamp01(app.spacing) * 26.0;

    let num_spring = spring_out(clamp01(flash * 3.0), 12.0, 0.58);
    let num_y = (1.0 - num_spring) * 10.0;
    let num_color = mix(INK, tint(VIOLET_SOFT, 0.3), flash.min(1.0));

    let mut app_stack = Stack::new()
        .push(
            Positioned::new().left(96.0).top(88.0 + spacing_shift * 0.4).width(640.0).height(52.0).child(
                Text::new(heading).style(
                    TextStyle::new(38.0)
                        .weight(FontWeight::Medium)
                        .letter_spacing(1.0)
                        .color(if heading_a > 0.02 && heading_a < 0.98 {
                            tint(VIOLET_SOFT, 0.2)
                        } else {
                            INK
                        }),
                ),
            ),
        )
        .push(
            Positioned::new().left(98.0).top(148.0 + spacing_shift).width(600.0).height(30.0).child(
                Text::new(format!("Tapped {} times", number))
                    .style(TextStyle::new(21.0).monospace().color(MUTED)),
            ),
        )
        .push(
            Positioned::new()
                .left(0.0)
                .top(196.0 + num_y + spacing_shift)
                .width(pane_w)
                .height(190.0)
                .child(
                    Text::new(number.to_string())
                        .style(
                            TextStyle::new(148.0)
                                .monospace()
                                .weight(FontWeight::Medium)
                                .letter_spacing(2.0)
                                .color(num_color),
                        )
                        .align(TextAlign::Center),
                ),
        );

    // The button — its rect is probe-grade (see button_rect); the column's
    // spacing re-flow (S12) shifts it down as the layout breathes.
    let press = 1.0 - 0.06 * flash;
    let br = button_rect();
    app_stack = app_stack.push(
        Positioned::new()
            .left(br.left)
            .top(br.top - 40.0 + spacing_shift)
            .width(br.width())
            .height(br.height())
            .child(
                Container::new()
                    .color(alpha(VIOLET, 0.20 * press))
                    .radius(12.0)
                    .border(vieww_foundation::Border::new(alpha(VIOLET_SOFT, 0.55), 1.4))
                    .child(
                        Text::new("Add one")
                            .style(
                                TextStyle::new(23.0)
                                    .weight(FontWeight::Medium)
                                    .color(tint(VIOLET_SOFT, 0.35)),
                            )
                            .align(TextAlign::Center),
                    ),
            ),
    );

    // The dial — an arc gauge, count over the ladder's full height.
    if clamp01(app.dial) > 0.01 {
        let dial = clamp01(app.dial);
        let cx = 700.0;
        let cy = 150.0;
        let lad = app.number.max(1);
        app_stack = app_stack.push(
            Positioned::new().left(0.0).top(0.0).width(pane_w).height(PV_H).child(
                Opacity::new(dial).child(Painting::sized(
                    Size::new(pane_w, PV_H),
                    PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                        let r = 62.0;
                        book.stroke(circle_local(cx, cy, r), alpha(Color::WHITE, 0.10), 7.0);
                        let sweep = (number as f32 / lad as f32).clamp(0.0, 1.0);
                        if sweep > 0.001 {
                            let mut p = vieww_foundation::Path::new();
                            p.move_to(Offset::new(cx, cy - r));
                            for i in 0..=40 {
                                let a = -std::f32::consts::FRAC_PI_2
                                    + i as f32 / 40.0 * sweep * std::f32::consts::TAU;
                                p.line_to(Offset::new(cx + a.cos() * r, cy + a.sin() * r));
                            }
                            book.stroke(p, alpha(VIOLET_SOFT, 0.85), 7.0);
                        }
                        book.circle(Offset::new(cx, cy), 4.0, tint(VIOLET_SOFT, 0.3));
                    }),
                )),
            ),
        );
    }

    // The spring toy — a bob on a spring line, phase from the session
    // clock. It never restarts (the carry's whole claim).
    if clamp01(app.spring) > 0.01 {
        let spring_p = clamp01(app.spring);
        let spring_abs = app.spring_abs;
        let disp = (spring_abs * 2.4).sin() * 26.0;
        let bx = 240.0;
        let by0 = 560.0;
        app_stack = app_stack.push(
            Positioned::new().left(0.0).top(0.0).width(pane_w).height(PV_H).child(
                Opacity::new(spring_p).child(Painting::sized(
                    Size::new(pane_w, PV_H),
                    PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                        let by = by0 + disp;
                        let mut p = vieww_foundation::Path::new();
                        p.move_to(Offset::new(bx, by0 - 64.0));
                        for i in 0..12 {
                            let k = (i + 1) as f32 / 12.0;
                            let y = by0 - 64.0 + k * (64.0 + (by - by0));
                            let wob = if i % 2 == 0 { 12.0 } else { -12.0 };
                            p.line_to(Offset::new(bx + wob, y));
                        }
                        p.line_to(Offset::new(bx, by));
                        book.stroke(p, alpha(MUTED, 0.55), 1.6);
                        book.circle(Offset::new(bx, by + 8.0), 11.0, tint(VIOLET_SOFT, 0.4));
                        book.stroke(circle_local(bx, by + 8.0, 11.0), alpha(Color::WHITE, 0.25), 1.0);
                        book.rect(xywh(bx - 22.0, by0 - 70.0, 44.0, 5.0), alpha(Color::WHITE, 0.18));
                    }),
                )),
            ),
        );
    }

    // The error boundary — a boundary, not a crash. The preview holds its
    // last good frame beneath the card: nothing is lost, nothing breaks.
    if clamp01(app.error) > 0.01 {
        let e = clamp01(app.error);
        app_stack = app_stack.push(
            Positioned::new().left(96.0).top(96.0).width(660.0).height(420.0).child(
                Opacity::new(e).child(Painting::sized(
                    Size::new(660.0, 420.0),
                    PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
                        book.rrect(xywh(0.0, 0.0, 660.0, 420.0), 16.0, alpha(Color::rgb(40, 16, 20), 0.94));
                        book.stroke_rrect(xywh(0.0, 0.0, 660.0, 420.0), 16.0, alpha(RED, 0.45), 1.4);
                        book.rect(xywh(0.0, 0.0, 660.0, 4.0), alpha(RED, 0.8 * e));
                    }),
                )),
            ),
        );
        app_stack = app_stack
            .push(
                Positioned::new().left(136.0).top(150.0).width(560.0).height(40.0).child(
                    Text::new("boundary").style(
                        TextStyle::new(30.0)
                            .monospace()
                            .letter_spacing(3.0)
                            .color(tint(RED, 0.25)),
                    ),
                ),
            )
            .push(
                Positioned::new().left(136.0).top(206.0).width(540.0).height(90.0).child(
                    Text::new(
                        "expected a value after \u{201c}showing\u{d}\nthe preview holds your last good frame",
                    )
                    .style(TextStyle::new(19.0).monospace().color(alpha(INK, 0.8))),
                ),
            );
    }

    // The dormant skeleton — before the first paint, the pane is a dim
    // wireframe of what it is waiting to become.
    let skeleton = Painting::sized(
        Size::new(pane_w, PV_H),
        PaintWith::new(move |book: &mut Sketchbook, _s: Size| {
            let a = 0.16 * (1.0 - alive);
            if a <= 0.005 {
                return;
            }
            book.rrect(xywh(96.0, 96.0, 240.0, 34.0), 6.0, alpha(Color::WHITE, a));
            book.rrect(xywh(98.0, 152.0, 300.0, 18.0), 5.0, alpha(Color::WHITE, a * 0.7));
            book.rrect(xywh(360.0, 210.0, 180.0, 120.0), 10.0, alpha(Color::WHITE, a));
            let br = button_rect();
            book.rrect(
                xywh(br.left, br.top - 40.0, br.width(), br.height()),
                12.0,
                alpha(VIOLET, a * 0.8),
            );
            book.stroke_styled(
                circle_path(br.left + br.width() + 70.0, br.top - 8.0, 14.0, 36),
                alpha(MUTED, a * 2.4),
                2.2,
                vieww_foundation::StrokeStyle::rounded()
                    .dash(vieww_foundation::Dash::even(6.0).offset(alive * 40.0)),
            );
        }),
    );

    let bloom_a = 0.34 * (1.0 - alive).max(0.0) + if alive >= 0.999 { 0.0 } else { 0.05 };
    Stack::new()
        .push(
            Positioned::new().left(0.0).top(0.0).width(pane_w).height(PV_H).child(Painting::sized(
                Size::new(pane_w, PV_H),
                PaintWith::new(move |book: &mut Sketchbook, s: Size| {
                    if alive > 0.001 && alive < 0.999 {
                        super::glow(
                            book,
                            s.width * 0.5,
                            s.height * 0.42,
                            340.0 + 260.0 * (1.0 - alive),
                            VIOLET,
                            bloom_a,
                        );
                    }
                }),
            )),
        )
        .push(
            Positioned::new().left(0.0).top(0.0).width(pane_w).height(PV_H).child(skeleton),
        )
        .push(
            Positioned::new().left(0.0).top(0.0).width(pane_w).height(PV_H).child(
                Opacity::new(alive).child(app_stack),
            ),
        )
        .into()
}

