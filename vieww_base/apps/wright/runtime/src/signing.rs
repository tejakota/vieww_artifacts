//! Receipt signing keys (ADR-025): where the key lives, honestly named.
//!
//! A signature is only worth what its key management is, so the source
//! of the key is recorded in the receipt itself:
//!
//! 1. `keychain:wright/receipt-signing` — the OS keychain, the right
//!    home for a person's machine (`wright secret set` puts it there).
//!    Provenance in the receipt: `"os-keychain"`.
//! 2. `WRIGHT_SECRET_WRIGHT_RECEIPT_SIGNING` — the env override CI and
//!    servers use, 32 bytes of hex. Provenance: `"env"`.
//! 3. A generated key, stored under Wright's own home with 0600
//!    permissions so `wright verify` keeps working on this machine.
//!    This is the no-keychain, no-env fallback (a container, a CI box),
//!    and it says so: Provenance `"local:generated"` — weaker than an
//!    OS keychain (any process on the machine can read it), never
//!    silently equal to one.
//!
//! The key is a 32-byte Ed25519 seed. Values in the keychain/env are
//! 64 hex chars; anything else is refused loudly, never truncated.

use std::path::PathBuf;

use crate::config::wright_home;
use crate::secrets;
use wright_core::ed25519;

/// The keychain reference a person's machine uses.
pub const KEY_REF: &str = "keychain:wright/receipt-signing";

/// Where a key came from — recorded in the receipt, so a verifier knows
/// what the signature is worth.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Provenance {
    /// The OS keychain: the real thing.
    OsKeychain,
    /// An environment override: CI, servers.
    Env,
    /// Generated by Wright, kept in Wright's own home. Honest fallback:
    /// local to this machine, weaker than a keychain, and never silent.
    LocalGenerated,
    /// An ephemeral key that lasted one process (used by tests).
    Ephemeral,
}

impl Provenance {
    pub fn as_str(&self) -> &'static str {
        match self {
            Provenance::OsKeychain => "os-keychain",
            Provenance::Env => "env",
            Provenance::LocalGenerated => "local:generated",
            Provenance::Ephemeral => "ephemeral",
        }
    }
}

/// A resolved signing key: the Ed25519 seed plus where it came from.
pub struct SigningKey {
    seed: [u8; 32],
    pub provenance: Provenance,
}

/// 32-byte hex -> seed, or a plain sentence about why not.
fn from_hex(s: &str) -> Result<[u8; 32], String> {
    let clean: String = s.chars().filter(|c| !c.is_ascii_whitespace()).collect();
    if clean.len() != 64 || !clean.bytes().all(|b| b.is_ascii_hexdigit()) {
        return Err("the signing key must be 32 bytes (64 hex characters)".into());
    }
    let mut seed = [0u8; 32];
    for (i, b) in seed.iter_mut().enumerate() {
        *b = u8::from_str_radix(&clean[i * 2..i * 2 + 2], 16).map_err(|e| e.to_string())?;
    }
    Ok(seed)
}

pub fn to_hex(seed: &[u8; 32]) -> String {
    seed.iter().map(|b| format!("{b:02x}")).collect()
}

fn file_path() -> PathBuf {
    wright_home().join("keys").join("receipt-signing.seed")
}

impl SigningKey {
    /// The public half, as hex — the receipt carries it so anyone can
    /// verify without asking Wright for anything.
    pub fn public_hex(&self) -> String {
        to_hex(&ed25519::public_key(&self.seed))
    }

    /// The raw seed, for `wright recipe sign` (the same process that
    /// signs receipts; the key never crosses a process boundary in
    /// plaintext beyond what the keychain itself already allows).
    pub fn seed_for_signing(&self) -> [u8; 32] {
        self.seed
    }

    pub fn provenance_str(&self) -> &'static str {
        self.provenance.as_str()
    }

    /// Sign bytes; the signature is 64 raw bytes.
    pub fn sign(&self, bytes: &[u8]) -> [u8; 64] {
        ed25519::sign(&self.seed, bytes)
    }

    /// Verify with a public key given as hex.
    pub fn verify(public_hex: &str, bytes: &[u8], sig: &[u8; 64]) -> bool {
        match from_hex(public_hex) {
            Ok(pk) => {
                let mut arr = [0u8; 32];
                arr.copy_from_slice(&pk);
                ed25519::verify(&arr, bytes, sig)
            }
            Err(_) => false,
        }
    }

    /// Resolve the machine's key: env override, then the OS keychain,
    /// then a generated file key — each reported honestly by its
    /// provenance. `WRIGHT_EPHEMERAL_SIGNING=1` forces an in-memory key
    /// (tests and throwaway demos), reported honestly; it is generated
    /// once per process so a run's receipts verify against each other.
    pub fn resolve() -> Result<SigningKey, String> {
        static EPHEMERAL: std::sync::OnceLock<[u8; 32]> = std::sync::OnceLock::new();
        if std::env::var("WRIGHT_EPHEMERAL_SIGNING")
            .map(|v| v == "1")
            .unwrap_or(false)
        {
            let seed = match EPHEMERAL.get() {
                Some(s) => *s,
                None => {
                    let fresh = generate_seed()?;
                    *EPHEMERAL.get_or_init(|| fresh)
                }
            };
            return Ok(SigningKey {
                seed,
                provenance: Provenance::Ephemeral,
            });
        }
        // 1. The env override — CI and servers (`secrets::env_name` gives
        //    the convention: WRIGHT_SECRET_WRIGHT_RECEIPT_SIGNING).
        if let Ok(name) = secrets::env_name(KEY_REF) {
            if let Ok(v) = std::env::var(&name) {
                let seed = from_hex(v.trim())?;
                return Ok(SigningKey {
                    seed,
                    provenance: Provenance::Env,
                });
            }
        }
        // 2. The OS keychain.
        if let Ok(v) = secrets::resolve(KEY_REF) {
            let seed = from_hex(v.expose())?;
            return Ok(SigningKey {
                seed,
                provenance: Provenance::OsKeychain,
            });
        }
        // 3. A generated file key (honest about being weaker).
        let p = file_path();
        if let Ok(text) = std::fs::read_to_string(&p) {
            let seed = from_hex(text.trim())?;
            return Ok(SigningKey {
                seed,
                provenance: Provenance::LocalGenerated,
            });
        }
        let seed = generate_seed()?;
        if let Some(dir) = p.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        // Created with 0600 from the first byte: written first and
        // narrowed afterwards, the key sat world-readable in between.
        let mut o = std::fs::OpenOptions::new();
        o.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            o.mode(0o600);
        }
        {
            use std::io::Write;
            let mut f = o
                .open(&p)
                .map_err(|e| format!("cannot create the signing key {}: {e}", p.display()))?;
            f.write_all(to_hex(&seed).as_bytes())
                .and_then(|_| f.sync_all())
                .map_err(|e| format!("cannot write the signing key {}: {e}", p.display()))?;
        }
        Ok(SigningKey {
            seed,
            provenance: Provenance::LocalGenerated,
        })
    }

    /// This machine's key if it already has one — never generating one
    /// (verifying a receipt must not mint a key as a side effect).
    pub fn existing() -> Option<SigningKey> {
        if std::env::var("WRIGHT_EPHEMERAL_SIGNING").map(|v| v == "1").unwrap_or(false) {
            return SigningKey::resolve().ok();
        }
        if let Ok(name) = secrets::env_name(KEY_REF) {
            if let Ok(v) = std::env::var(&name) {
                return from_hex(v.trim()).ok().map(|seed| SigningKey { seed, provenance: Provenance::Env });
            }
        }
        if let Ok(v) = secrets::resolve(KEY_REF) {
            if let Ok(seed) = from_hex(v.expose()) {
                return Some(SigningKey { seed, provenance: Provenance::OsKeychain });
            }
        }
        let text = std::fs::read_to_string(file_path()).ok()?;
        from_hex(text.trim()).ok().map(|seed| SigningKey { seed, provenance: Provenance::LocalGenerated })
    }
}

/// Who a public key belongs to, as far as THIS machine knows — or why it
/// is not trusted. A valid signature proves the bytes were not changed
/// after signing; only a pinned key says who signed them (anyone can
/// make a fresh key and re-sign an edited receipt or recipe).
///
/// Trusted, in order: a key passed on the command line (`--key`), a
/// `trust "name" key="..."` line in config.kdl, and this machine's own
/// signing key.
pub fn signer(public_hex: &str, pinned_now: &[String]) -> Result<String, String> {
    let k = public_hex.trim().to_ascii_lowercase();
    if pinned_now.iter().any(|p| p.trim().eq_ignore_ascii_case(&k)) {
        return Ok("the key you named with --key".into());
    }
    if let Ok(cfg) = crate::config::Config::load() {
        if let Some(name) = cfg.trusts(&k) {
            return Ok(format!("{name} (pinned in config.kdl)"));
        }
    }
    if let Some(own) = SigningKey::existing() {
        if own.public_hex() == k {
            return Ok("this machine's own signing key".into());
        }
    }
    Err(format!(
        "the key {}… is not one this machine trusts. Anyone can sign with a fresh key, so a signature alone does not say who made this. \
         Ask the signer for their public key and check it with --key <64 hex>, or pin it: add `trust \"<who>\" key=\"{k}\"` to config.kdl (or `wright trust add \"<who>\" {k}`)",
        &k[..k.len().min(12)]
    ))
}

/// 32 bytes from the operating system's random source.
///
/// Unix: `/dev/urandom` (the kernel CSPRNG; never blocks once seeded).
/// Elsewhere: the standard library's hasher keys, which std seeds from
/// the OS generator (`ProcessPrng` on Windows), stretched through
/// SHA-512 with a counter — no `unsafe`, no crate, and nothing derived
/// from the clock or the process id.
fn generate_seed() -> Result<[u8; 32], String> {
    let mut seed = [0u8; 32];
    #[cfg(unix)]
    {
        use std::io::Read;
        let mut f = std::fs::File::open("/dev/urandom")
            .map_err(|e| format!("cannot read the system random source: {e}"))?;
        f.read_exact(&mut seed)
            .map_err(|e| format!("cannot read the system random source: {e}"))?;
        Ok(seed)
    }
    #[cfg(not(unix))]
    {
        use std::hash::{BuildHasher, Hasher};
        let mut material = Vec::with_capacity(16 * 8);
        for i in 0..16u64 {
            // Each RandomState::new() carries OS-seeded keys.
            let mut h = std::collections::hash_map::RandomState::new().build_hasher();
            h.write_u64(i);
            material.extend_from_slice(&h.finish().to_le_bytes());
        }
        let digest = wright_core::sha512::sha512(&[&material]);
        seed.copy_from_slice(&digest[..32]);
        Ok(seed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Env vars are process-wide and tests run in parallel: every test
    /// that flips one takes this lock, so the settings they see are the
    /// settings they set.
    static ENV_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

    fn tmp_home(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("wright-signing-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn hex_round_trips_and_bad_lengths_are_refused() {
        let seed = [0xabu8; 32];
        let hex = to_hex(&seed);
        assert_eq!(hex.len(), 64);
        assert_eq!(from_hex(&hex).unwrap(), seed);
        assert!(from_hex("abcd").is_err(), "too short");
        assert!(from_hex(&"z".repeat(64)).is_err(), "not hex");
        assert!(
            from_hex(&format!("{} ", hex)).is_ok(),
            "whitespace tolerated"
        );
    }

    #[test]
    fn sign_and_verify_with_the_public_key() {
        let k = SigningKey {
            seed: [3u8; 32],
            provenance: Provenance::Ephemeral,
        };
        let msg = b"wright.run-receipt/2 body";
        let sig = k.sign(msg);
        assert!(SigningKey::verify(&k.public_hex(), msg, &sig));
        assert!(!SigningKey::verify(&k.public_hex(), b"tampered", &sig));
        assert!(!SigningKey::verify("bad", msg, &sig), "bad key hex refuses");
    }

    #[test]
    fn ephemeral_mode_is_honest_and_generate_works() {
        let _guard = ENV_LOCK.lock().unwrap_or_else(|p| p.into_inner());
        std::env::set_var("WRIGHT_EPHEMERAL_SIGNING", "1");
        let k = SigningKey::resolve().unwrap();
        assert_eq!(k.provenance, Provenance::Ephemeral);
        let other = SigningKey::resolve().unwrap();
        assert_eq!(
            k.public_hex(),
            other.public_hex(),
            "same process, same ephemeral key"
        );
        std::env::remove_var("WRIGHT_EPHEMERAL_SIGNING");
        // generate_seed reads the OS random source: two draws differ.
        let a = generate_seed().unwrap();
        let b = generate_seed().unwrap();
        assert_ne!(a, b, "two draws from the OS generator differ");
    }

    #[test]
    fn generated_file_key_persists_under_wright_home() {
        let _guard = ENV_LOCK.lock().unwrap_or_else(|p| p.into_inner());
        std::env::remove_var("WRIGHT_EPHEMERAL_SIGNING");
        let home = tmp_home("file-key");
        std::env::set_var("WRIGHT_HOME", &home);
        let k1 = SigningKey::resolve().unwrap();
        assert_eq!(k1.provenance, Provenance::LocalGenerated);
        let k2 = SigningKey::resolve().unwrap();
        assert_eq!(
            k1.public_hex(),
            k2.public_hex(),
            "the generated key is stable on this machine"
        );
        // and it signed something verifiable
        let msg = b"receipt";
        let sig = k1.sign(msg);
        assert!(SigningKey::verify(&k1.public_hex(), msg, &sig));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(file_path()).unwrap().permissions().mode() & 0o777;
            assert_eq!(mode, 0o600, "only this user may read the key");
        }
        // trust: this machine's own key is trusted, a stranger's is not
        assert!(signer(&k1.public_hex(), &[]).is_ok());
        let stranger = to_hex(&ed25519::public_key(&[9u8; 32]));
        let why = signer(&stranger, &[]).unwrap_err();
        assert!(why.contains("not one this machine trusts"), "{why}");
        assert!(signer(&stranger, std::slice::from_ref(&stranger)).is_ok(), "--key pins it");
        std::env::remove_var("WRIGHT_HOME");
    }
}
